import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('assets/js/catalogue-data.js','utf8'),context);
fs.mkdirSync('tmp/pdfs',{recursive:true});
fs.writeFileSync('tmp/pdfs/catalogue-data.json',JSON.stringify(context.window.MACatalogueData));
const localPython=path.resolve('tmp/pdf-venv/Scripts/python.exe');
const python=process.env.PYTHON || (fs.existsSync(localPython)?localPython:'python');
execFileSync(python,['scripts/create-range-catalogue.py'],{stdio:'inherit'});
